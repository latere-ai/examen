package work

import (
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"testing"
	"time"
)

var update = flag.Bool("update", false, "rewrite the formal models under formal/")

// gradingHoldConstants is formal/GradingHoldConstants.tla: the hold of a
// grading job and the longest its run takes, for checks and for judgments,
// in the whole minutes the TLA+ model counts in. The hold rounds down and
// the run up, so the model never gives a run more room than the code does.
func gradingHoldConstants() string {
	minutes := func(d time.Duration, up bool) int {
		if up {
			return int((d + time.Minute - 1) / time.Minute)
		}
		return int(d / time.Minute)
	}
	return fmt.Sprintf(`\* Code generated by TestGradingHoldConstants in internal/work. DO NOT EDIT.
------------------------- MODULE GradingHoldConstants -------------------------
ChecksHold == %d
ChecksBudget == %d
JudgeHold == %d
JudgeBudget == %d
=============================================================================
`, minutes(holdChecks, false), minutes(checksBound, true), minutes(holdJudge, false), minutes(judgeBound, true))
}

// TestGradingHoldConstants holds formal/GradingHoldConstants.tla to the Go
// constants, so the tla gate checks formal/GradingHold.tla against the holds
// and run bounds the grading loop runs with. Rerun with -update after
// changing one.
func TestGradingHoldConstants(t *testing.T) {
	path := filepath.Join("..", "..", "formal", "GradingHoldConstants.tla")
	want := gradingHoldConstants()
	if *update {
		if err := os.WriteFile(path, []byte(want), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	got, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("read %s: %v; rerun with -update", path, err)
	}
	if string(got) != want {
		t.Fatalf("%s differs from the grading constants; rerun go test ./internal/work -run TestGradingHoldConstants -update\n--- want\n%s--- got\n%s", path, want, got)
	}
}
